S = requests.Session()
S.headers["User-Agent"] = "MCR-GeoChem/1.0 (open research compilation)"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def log(source_id, path, url, note=""):
    rows = []
    if os.path.exists(LOG):
        with open(LOG, newline="", encoding="utf-8") as f:
            rows = [r for r in csv.DictReader(f) if r["file"] != os.path.relpath(path, RAW)]
    rows.append(dict(source_id=source_id, file=os.path.relpath(path, RAW), url=url,
                     access_date=dt.date.today().isoformat(), bytes=os.path.getsize(path),
                     sha256=sha256(path), license=LIC[source_id], citation=CIT[source_id], note=note))
    with open(LOG, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=LOG_FIELDS)
        w.writeheader()
        w.writerows(sorted(rows, key=lambda r: (r["source_id"], r["file"])))
    print(f"  logged {os.path.relpath(path, RAW)} ({os.path.getsize(path):,} bytes)")


def get(url, path, source_id, refresh, note="", method="GET", data=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path) and not refresh:
        print(f"  exists: {os.path.relpath(path, RAW)}")
        return path
    for attempt in range(4):
        try:
            r = S.request(method, url, data=data, stream=True, timeout=300)
            r.raise_for_status()
            with open(path + ".part", "wb") as f:
                for chunk in r.iter_content(1 << 20):
                    f.write(chunk)
            os.replace(path + ".part", path)
            log(source_id, path, url, note)
            return path
        except Exception as e:  # network hiccup: retry with backoff
            print(f"  retry {attempt + 1}: {e}")
            time.sleep(5 * (attempt + 1))
    sys.exit(f"FAILED: {url}")


def arcgis_query(base, where, path, source_id, refresh, out_sr=4326, geometry=False, note=""):
    """Page through an ArcGIS feature service query and save all features as one JSON file."""
    if os.path.exists(path) and not refresh:
        print(f"  exists: {os.path.relpath(path, RAW)}")
        return path
    feats, offset = [], 0
    fmt = "geojson" if geometry else "json"
    while True:
        params = dict(where=where, outFields="*", returnGeometry=str(geometry).lower(),
                      outSR=out_sr, resultOffset=offset, resultRecordCount=1000,
                      orderByFields="OBJECTID", f=fmt)
        r = S.get(base + "/query", params=params, timeout=300)
        r.raise_for_status()
        d = r.json()
        if "error" in d:
            sys.exit(f"ArcGIS error: {d['error']}")
        batch = d["features"]
        feats += batch
        if not batch or not (d.get("exceededTransferLimit") or d.get("properties", {}).get("exceededTransferLimit")):
            break
        offset += len(batch)
    out = {"type": "FeatureCollection", "features": feats} if geometry else {"features": feats}
    out["_query"] = {"service": base, "where": where, "retrieved": dt.datetime.now(dt.timezone.utc).isoformat()}
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f)
    url = base + "/query?where=" + where
    log(source_id, path, url, note or f"{len(feats)} features via ArcGIS REST query")
    return path


def georoc_minerals(refresh):
    """Download each GEOROC mineral file once, keep only rows from the study region, delete the rest."""
    import pandas as pd
    out = os.path.join(RAW, "georoc", "georoc_minerals_mcr_region.csv")
    if os.path.exists(out) and not refresh:
        print("  exists: georoc/georoc_minerals_mcr_region.csv")
        return
    lst = S.get("https://data.goettingen-research-online.de/api/datasets/:persistentId/versions/:latest/files",
                params={"persistentId": "doi:10.25625/SGFTFN"}, timeout=120).json()["data"]
    keep, manifest = [], []
    for item in sorted(lst, key=lambda x: x["dataFile"]["filename"]):
        fid, name = item["dataFile"]["id"], item["dataFile"]["filename"]
        print(f"  scanning {name} ...", flush=True)
        tmp = os.path.join(RAW, "georoc", "_tmp_" + name)
        for attempt in range(5):  # download to a temporary file, then filter; robust to dropped streams
            try:
                with S.get(GRO + str(fid), stream=True, timeout=600) as r:
                    r.raise_for_status()
                    with open(tmp, "wb") as f:
                        for block in r.iter_content(1 << 22):
                            f.write(block)
                break
            except Exception as e:
                print(f"    retry {attempt + 1}: {e}", flush=True)
                time.sleep(10 * (attempt + 1))
        else:
            sys.exit(f"FAILED: {name}")
        n_in = n_keep = 0
        for chunk in pd.read_csv(tmp, encoding="latin1", chunksize=100000, low_memory=False,
                                 dtype=str, on_bad_lines="skip"):
            n_in += len(chunk)
            loc = chunk.get("LOCATION", pd.Series("", index=chunk.index)).fillna("").str.upper()
            lat = pd.to_numeric(chunk.get("LATITUDE (MIN.)"), errors="coerce")
            lon = pd.to_numeric(chunk.get("LONGITUDE (MIN.)"), errors="coerce")
            in_box = lat.between(BBOX["lat_min"], BBOX["lat_max"]) & lon.between(BBOX["lon_min"], BBOX["lon_max"])
            txt = loc.str.contains("MIDCONTINENT RIFT|KEWEENAW|DULUTH COMPLEX", regex=True)
            sel = chunk[in_box | txt].copy()
            if len(sel):
                sel.insert(0, "GEOROC_FILE", name)
                keep.append(sel)
                n_keep += len(sel)
        os.remove(tmp)
        manifest.append(dict(file=name, datafile_id=fid, rows_scanned=n_in, rows_kept=n_keep,
                             url=GRO + str(fid)))
    df = pd.concat(keep, ignore_index=True) if keep else pd.DataFrame()
    df.to_csv(out, index=False)
    pd.DataFrame(manifest).to_csv(os.path.join(RAW, "georoc", "georoc_minerals_scan_manifest.csv"), index=False)
    log("S5", out, "https://doi.org/10.25625/SGFTFN",
        f"Region filter of {len(manifest)} mineral files: lat {BBOX['lat_min']}-{BBOX['lat_max']}, "
        f"lon {BBOX['lon_min']}-{BBOX['lon_max']}, or LOCATION mentions Midcontinent Rift/Keweenaw/Duluth; "
        f"{len(df)} rows kept; per-file counts in georoc_minerals_scan_manifest.csv")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true", help="re-download even if files exist")
    ap.add_argument("--skip-minerals", action="store_true", help="skip the 2.5 GB GEOROC mineral scan")
    a = ap.parse_args()
    st = ",".join(f"'{s}'" for s in STATES)

    print("S1 USGS NGDB 1962-2023 (public feature service of the data release)")
    for layer, name in [(1, "rock"), (3, "mineral"), (4, "geologic_material")]:
        arcgis_query(f"{NGDB_FS}/{layer}", f"state IN ({st})",
                     os.path.join(RAW, "ngdb", f"ngdb_{name}_MI_MN_WI.json"), "S1", a.refresh,
                     note=f"Layer {layer} Geochem_{name}; same release as doi:10.5066/P1FXE9GK. "
                          "ScienceBase bulk files require login, so the public USGS feature service "
                          "(found via https://alaska.usgs.gov/science/geology/geochem_portal/) was used.")
    get(SB + "63a107a0d34e0de3a1f2795f?f=__disk__07%2F80%2F07%2F0780071539c805206db060e6b944eb8614741ec7",
        os.path.join(RAW, "ngdb", "geochem_metadata.xml"), "S1", a.refresh, "FGDC metadata of the release")

    print("S2 USGS Duluth Complex drill core release")
    item = S.get("https://www.sciencebase.gov/catalog/item/675b332fd34e08c81ed96c4c?format=json", timeout=60).json()
    for f in item["files"]:
        get(f["downloadUri"], os.path.join(RAW, "usgs_duluth", f["name"]), "S2", a.refresh)

    print("S3 USGS Earth MRI geochemistry v12")
    item = S.get("https://www.sciencebase.gov/catalog/item/601963c6d34edf5c66f0d0e5?format=json", timeout=60).json()
    for f in item["files"]:
        if f["name"].endswith(".accdb"):
            continue  # same content as EMRI_Data.csv
        get(f["downloadUri"], os.path.join(RAW, "emri", f["name"]), "S3", a.refresh)

    print("S7 USGS Woodruff (2019) Duluth Complex basal contact bedrock")
    item = S.get("https://www.sciencebase.gov/catalog/item/5d2f40f3e4b038fabe24db02?format=json", timeout=60).json()
    for f in item["files"]:
        if f["name"] in ("Bedrock.csv", "Analytical_methods_LLD.csv") or f["name"].endswith(".xml"):
            get(f["downloadUri"], os.path.join(RAW, "usgs_woodruff2019", f["name"]), "S7", a.refresh)

    print("S4 GEOROC Continental Flood Basalts: Midcontinent Rift System - Keweenawan")
    get(GRO + "218710", os.path.join(RAW, "georoc", "2026-09-WSTPOX_MIDCONTINENT_RIFT_SYSTEM-KEWEENAWAN.csv"),
        "S4", a.refresh, "GRO.data datafile id 218710")

    print("S6 EarthChem Library 1501, Portage Lake Volcanics")
    get("https://ecl.earthchem.org/dl_multi.php",
        os.path.join(RAW, "earthchem", "1501-1_ECL_Davis_et_al_Portage_Lake_volcanics.xlsx"), "S6", a.refresh,
        "POST id=1501 from landing page https://ecl.earthchem.org/view.php?id=1501", method="POST",
        data=dict(id="1501", verifySubmit="yes", system="ec", dlFormat="single",
                  filename="1501-1_ECL_Davis_et_al_XRF_and_LA-ICP-MS_analysis_of_the_Portage_Lake_volcanics.xlsx"))

    print("R1 USGS AGDB4 method dictionary (same USGS method-code system as the NGDB)")
    agdir = os.path.join(RAW, "agdb4")
    want = ["AnalyticMethod", "AnalyticMethod_Biblio", "Parameter", "Parameter_Rank", "DataDictionary"]
    if a.refresh or not all(os.path.exists(os.path.join(agdir, w + ".txt")) for w in want):
        import zipfile
        item = S.get("https://www.sciencebase.gov/catalog/item/6500b2bed34ed30c2057f99b?format=json", timeout=60).json()
        url = [f["downloadUri"] for f in item["files"] if f["name"] == "AGDB4_text.zip"][0]
        zpath = get(url, os.path.join(agdir, "AGDB4_text.zip"), "R1", True, "temporary; only method tables kept")
        with zipfile.ZipFile(zpath) as z:
            for w in want:
                with z.open(f"AGDB4_text/{w}.txt") as src, open(os.path.join(agdir, w + ".txt"), "wb") as dst:
                    dst.write(src.read())
                log("R1", os.path.join(agdir, w + ".txt"), url, f"extracted from AGDB4_text.zip ({w}.txt)")
        os.remove(zpath)
        rows = list(csv.DictReader(open(LOG, encoding="utf-8")))
        with open(LOG, "w", newline="", encoding="utf-8") as f:
            wr = csv.DictWriter(f, fieldnames=LOG_FIELDS); wr.writeheader()
            wr.writerows(r for r in rows if not r["file"].endswith("AGDB4_text.zip"))
    else:
        print("  exists: agdb4 method tables")

    print("G1 USGS SGMC Mesoproterozoic map units in MI, MN, WI (rift footprint)")
    arcgis_query(SGMC_FS, f"STATE IN ({st}) AND (AGE_MIN LIKE '%Mesoproterozoic%' OR AGE_MAX LIKE '%Mesoproterozoic%')",
                 os.path.join(RAW, "sgmc", "sgmc_mesoproterozoic_MI_MN_WI.geojson"), "G1", a.refresh, geometry=True)

    print("G2 Census TIGER 2023 state boundaries")
    get("https://www2.census.gov/geo/tiger/TIGER2023/STATE/tl_2023_us_state.zip",
        os.path.join(RAW, "census", "tl_2023_us_state.zip"), "G2", a.refresh)

    if not a.skip_minerals:
        print("S5 GEOROC Minerals (streamed, region-filtered)")
        georoc_minerals(a.refresh)
    print("Done. Provenance in data/raw/provenance_log.csv")


if __name__ == "__main__":
    main()
