import requests

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "raw")
LOG = os.path.join(RAW, "provenance_log.csv")
LOG_FIELDS = ["source_id", "file", "url", "access_date", "bytes", "sha256",
              "license", "citation", "note"]

STATES = ("MI", "MN", "WI")
# Generous box around the three states, used only to pre-filter big global files.
BBOX = dict(lat_min=41.5, lat_max=49.5, lon_min=-97.5, lon_max=-82.0)

