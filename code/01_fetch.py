#!/usr/bin/env python3
"""01_fetch.py - download every raw input for MCR-GeoChem and log where it came from.

Plain-language note: this script downloads the public source files into data/raw/
and writes one line per file to data/raw/provenance_log.csv (source, URL, date,
size, checksum, license). You do not need to open it; run it with
`python code/01_fetch.py`. Re-running skips files already downloaded unless --refresh.
"""
